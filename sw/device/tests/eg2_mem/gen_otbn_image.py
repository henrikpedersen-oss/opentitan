"""An OTBN program's IMEM and DMEM images and symbols as a C header (eg2_mem's OTBN tests).

`otbn_binary` embeds an OTBN program as an RV32 object, which the CHERIoT linker refuses to link
with purecap code. The EG2 OTBN tests take the program as plain word tables instead, built the
same in both modes: `kEg2Otbn<Name>Imem` (IMEM from address 0), `kEg2Otbn<Name>Dmem` (DMEM from
address 0: initialised data, zeros for the rest up to the last allocated byte), and one
`kEg2Otbn<Name>_<sym>` constant per requested symbol (its DMEM address).

Usage: gen_otbn_image.py --name Smoke --sym gpr_state --sym wdr_state --out x.h prog.elf
"""

import argparse
import struct
import sys

SHF_ALLOC = 0x2
SHF_EXECINSTR = 0x4
SHT_PROGBITS = 1
SHT_SYMTAB = 2
SHT_NOBITS = 8


def sections(elf):
    if elf[:4] != b"\x7fELF" or elf[4] != 1 or elf[5] != 1:
        sys.exit("gen_otbn_image: not a 32-bit little-endian ELF")
    shoff, = struct.unpack_from("<I", elf, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    secs = []
    for i in range(shnum):
        (name, typ, flags, addr, off, size, link, info, align,
         entsize) = struct.unpack_from("<IIIIIIIIII", elf, shoff + i * shentsize)
        secs.append(dict(name=name, type=typ, flags=flags, addr=addr, off=off, size=size,
                         link=link, entsize=entsize))
    strtab = secs[shstrndx]
    for s in secs:
        end = elf.index(b"\0", strtab["off"] + s["name"])
        s["sname"] = elf[strtab["off"] + s["name"]:end].decode()
    return secs


def symbols(elf, secs):
    out = {}
    for s in secs:
        if s["type"] != SHT_SYMTAB:
            continue
        strs = secs[s["link"]]
        for i in range(s["size"] // s["entsize"]):
            name, value, size, info, other, shndx = struct.unpack_from(
                "<IIIBBH", elf, s["off"] + i * s["entsize"])
            end = elf.index(b"\0", strs["off"] + name)
            out[elf[strs["off"] + name:end].decode()] = value
    return out


def image(elf, secs, want_exec):
    mem = bytearray()
    for s in secs:
        if not s["flags"] & SHF_ALLOC or bool(s["flags"] & SHF_EXECINSTR) != want_exec:
            continue
        end = s["addr"] + s["size"]
        if len(mem) < end:
            mem.extend(b"\0" * (end - len(mem)))
        if s["type"] == SHT_PROGBITS:
            mem[s["addr"]:end] = elf[s["off"]:s["off"] + s["size"]]
    mem.extend(b"\0" * (-len(mem) % 4))
    return [struct.unpack_from("<I", mem, i)[0] for i in range(0, len(mem), 4)]


def table(name, words):
    lines = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(words), 6):
        lines.append("    " + " ".join(f"0x{w:08x}," for w in words[i:i + 6]))
    lines.append("};")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--name", required=True)
    p.add_argument("--sym", action="append", default=[])
    p.add_argument("--out", required=True)
    p.add_argument("elf")
    a = p.parse_args()
    elf = open(a.elf, "rb").read()
    secs = sections(elf)
    syms = symbols(elf, secs)
    imem = image(elf, secs, True)
    dmem = image(elf, secs, False)
    guard = f"EG2_OTBN_IMAGE_{a.name.upper()}_H_"
    out = [
        "// Generated by sw/device/tests/eg2_mem/gen_otbn_image.py from an otbn_binary ELF.",
        "// Do not edit.",
        f"#ifndef {guard}",
        f"#define {guard}",
        "#include <stdint.h>",
        table(f"kEg2Otbn{a.name}Imem", imem or [0]),
        table(f"kEg2Otbn{a.name}Dmem", dmem or [0]),
        f"enum {{ kEg2Otbn{a.name}ImemWords = {len(imem)}, "
        f"kEg2Otbn{a.name}DmemWords = {len(dmem)} }};",
    ]
    for s in a.sym:
        if s not in syms:
            sys.exit(f"gen_otbn_image: no symbol {s}")
        out.append(f"enum {{ kEg2Otbn{a.name}_{s} = 0x{syms[s]:x} }};")
    out.append(f"#endif  // {guard}")
    open(a.out, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
