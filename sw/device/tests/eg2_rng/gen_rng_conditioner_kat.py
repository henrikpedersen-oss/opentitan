"""Generate the vector table of chip_sw_eg2_rng_conditioner_kat.

Usage: gen_rng_conditioner_kat.py --out <table.h>

Each vector is a message of 32-bit words that software inserts into entropy_src's SHA-3
conditioner (FW_OV_WR_DATA, firmware override: extract and insert), and the 384-bit result it
must read back from ENTROPY_DATA: SHA3-384 of the words as little-endian bytes, the first word
first; the result's twelve words are the digest's bytes taken little-endian, in order.

The byte and word order is not stated by entropy_src's documentation. It is the order of
OpenTitan's own known answer for the conditioner (sw/device/tests/entropy_src_kat_impl.c,
kInputMsg / kExpectedDigest), which this generator reproduces before it writes anything: if the
order were different, the generator stops.

The digest is computed with Python's hashlib (FIPS 202 SHA3-384), not with digestpp, the C++
reference `make nist-cavp-ref` checks against the NIST SHA-3 vectors: digestpp is a header
library under hw/ip/kmac/dv/dpi/vendor with no Bazel target, and a host C++ tool would need one
outside this test's directory. Both implement FIPS 202; the legacy known answer above ties the
table to the hardware's documented test.

The messages: the legacy known answer, then words from a generator seeded with a constant, with
lengths of 2, 4, 16 words (shorter than a seed), 26 (the 832-bit SHA3-384 rate), 34 (beyond it), 64 (one
FIPS window of 2048 bits), 96 and 128 words. All lengths are even: the documents do not say how
an odd number of 32-bit words is packed into the conditioner's 64-bit input.
"""

import argparse
import hashlib
import random
import struct
from pathlib import Path

LEGACY_IN = [0xa52a0da9, 0xcae141b2, 0x6d5bab9d, 0x2c3e5cc0, 0x225afc93, 0x5d31a610,
             0x91b7f960, 0x0d566bb3, 0xef35e170, 0x94ba7d8e, 0x534eb741, 0x6b60b0da]
LEGACY_OUT = [0x1c88164a, 0x5ff456e1, 0x0845dbdf, 0xbe233f8e, 0x7a5a4c1b, 0x5d31356a,
              0x751cc536, 0x337375f2, 0x85a1ac19, 0x1333abd4, 0xf745fe0f, 0xc5bbf151]
# (length in words, length class): 0 short, 1 seed size, 2 window, 3 long
LENGTHS = [(2, 0), (4, 0), (16, 1), (26, 1), (34, 1), (64, 2), (96, 3), (128, 3)]


def conditioned(words):
    msg = b"".join(struct.pack("<I", w) for w in words)
    d = hashlib.sha3_384(msg).digest()
    return [struct.unpack("<I", d[i:i + 4])[0] for i in range(0, 48, 4)]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    if conditioned(LEGACY_IN) != LEGACY_OUT:
        raise SystemExit("gen_rng_conditioner_kat: the legacy known answer does not reproduce")
    rng = random.Random(0xe62c0d)
    vecs = [(LEGACY_IN, 1)]
    for n, cls in LENGTHS:
        vecs.append(([rng.getrandbits(32) for _ in range(n)], cls))
    words, table = [], []
    for msg, cls in vecs:
        table.append((len(words), len(msg), cls, conditioned(msg)))
        words.extend(msg)
    out = ["// Generated by sw/device/tests/eg2_rng/gen_rng_conditioner_kat.py; do not edit.",
           "#include <stdint.h>", "",
           "enum { kKatNum = %d, kKatWords = %d };" % (len(table), len(words)),
           "// The messages, back to back.",
           "static const uint32_t kKatMsg[kKatWords] = {"]
    for i in range(0, len(words), 6):
        out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
    out.append("};")
    out.append("// Per vector: offset into kKatMsg, length in words, length class.")
    out.append("static const uint16_t kKatOff[kKatNum] = {%s};" % ", ".join(str(t[0]) for t in table))
    out.append("static const uint16_t kKatLen[kKatNum] = {%s};" % ", ".join(str(t[1]) for t in table))
    out.append("static const uint8_t kKatClass[kKatNum] = {%s};" % ", ".join(str(t[2]) for t in table))
    out.append("// SHA3-384 of each message (little-endian words, the legacy known answer's order).")
    out.append("static const uint32_t kKatDigest[kKatNum][12] = {")
    for t in table:
        out.append("    {" + ", ".join("0x%08x" % w for w in t[3]) + "},")
    out.append("};")
    Path(args.out).write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
