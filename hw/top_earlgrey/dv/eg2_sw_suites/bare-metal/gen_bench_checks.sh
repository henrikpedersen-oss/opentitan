# Writes bench_checks.txt: the test images whose chip-bench sequence checks something itself. On the
# chip bench a test is its software plus a UVM sequence (uvm_test_seq in the dvsim test lists); most
# use chip_sw_base_vseq, which only loads and runs the software, but many have a sequence of their
# own that drives pins or reads outputs and checks them (DV_CHECK, `uvm_error). The SystemC model
# runs the software only, so for those tests a pass on the model leaves the bench's checks unrun;
# the report marks them "pass (bench checks not run)".
#
#   gen_bench_checks.sh      ->  bench_checks.txt (review the diff before committing it)
#
# Reads the EG2 fork (EG2_ROOT): hw/top_earlgrey/dv/*.hjson and the sequences under
# hw/top_earlgrey/dv/env. One line per image: <image> <sequence>.

set -euo pipefail
export LC_ALL=C
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$(dirname "${BASH_SOURCE[0]}")/../env.sh"   # EG2_ROOT
DV="${EG2_ROOT}/hw/top_earlgrey/dv"
OUT="${HERE}/bench_checks.txt"

# Every test entry's image (sw_images index 1) and sequence (chip_sw_base_vseq when it names
# none). An entry is the text between a line holding only "{" and the next holding only "}".
pairs=$(awk '
  /^[ \t]*\{[ \t]*$/ { seq = ""; img = ""; inside = 1; next }
  inside && /^[ \t]*uvm_test_seq:/ { seq = $2; gsub(/[",]/, "", seq) }
  inside && /\/\/sw\/device\// {  # the image lines (sw_images can span several)
    s = $0
    while (match(s, /:[a-z0-9_]+:1[":]/)) {
      img = substr(s, RSTART + 1, RLENGTH - 4)
      s = substr(s, RSTART + RLENGTH)
    }
  }
  inside && /^[ \t]*\}[ \t]*,?[ \t]*$/ {
    if (img != "") print img, (seq == "" ? "chip_sw_base_vseq" : seq)
    inside = 0
  }' "${DV}"/*.hjson | sort -u)

# A sequence checks something if its file has a result check outside comments: `uvm_error or any
# DV_CHECK, including DV_CHECK_*_FATAL (sysrst_ctrl's pad checks are fatal result checks). An image
# is listed only when
# every bench test that runs it has such a sequence: if one runs it with a plain sequence, the
# software alone is a complete test there (aes_smoketest, for example, also runs under the lockstep
# glitch sequence).
declare -A CHECKS
while read -r seq; do
  f=$(grep -rl "^class ${seq}\b" "${DV}/env" 2>/dev/null | head -1 || true)
  [[ -n "${f}" ]] && grep -v '^[[:space:]]*//' "${f}" | grep -q 'DV_CHECK\|`uvm_error' \
    && CHECKS[${seq}]=1
done < <(awk '{print $2}' <<< "${pairs}" | sort -u | grep -v '^chip_sw_base_vseq$')

{
  echo "# Generated by gen_bench_checks.sh from the EG2 fork's test lists: the images whose chip-bench"
  echo "# sequence checks something itself (not run on the SystemC model). <image> <sequence>"
  declare -A PLAIN FIRST
  while read -r img seq; do
    if [[ -n "${CHECKS[${seq}]:-}" ]]; then FIRST[${img}]=${FIRST[${img}]:-${seq}}; else PLAIN[${img}]=1; fi
  done <<< "${pairs}"
  for img in "${!FIRST[@]}"; do
    if [[ -z "${PLAIN[${img}]:-}" ]]; then echo "${img} ${FIRST[${img}]}"; fi
  done | sort
} > "${OUT}"
echo "== $(grep -vc '^#' "${OUT}") images with bench checks of their own, in ${OUT}"
