"""Build shared C rules with Bambu and compare production RTL decision cones.

The block's production file list supplies all RTL dependencies. Only the selected
cone is retained; hierarchy -check and SAT reject unresolved cells in the final miter.
Negative cases must produce a SAT counterexample, never merely a tool error.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import time

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
PACKAGES = ["hw/ip/prim/rtl/prim_util_pkg.sv", "hw/ip/prim/rtl/prim_secded_pkg.sv",
            "hw/ip/prim/rtl/prim_mubi_pkg.sv", "hw/top_earlgrey/rtl/top_pkg.sv",
            "hw/ip/tlul/rtl/tlul_pkg.sv"]
MAPS = {"eg2": (0x10000000, 0x10030000, 0x30000000, 0x30200000, 0x11000000),
        "small": (0x10000000, 0x10004000, 0x30000000, 0x30002000, 0x11000000)}


def lit(value):
    return f"32'h{value:08x}"


def miter(hls, inputs, arguments, width, body, comparison):
    ports = ",\n".join(f"input [{bits-1}:0] {name}_i" for name, bits in inputs.items())
    regs = "\n".join(f"reg [{bits-1}:0] {name};" for name, bits in inputs.items())
    latch = "\n".join(f"{name} <= {name}_i;" for name in inputs)
    args = ",\n".join(f".{name}({expr})" for name, expr in arguments.items())
    return f"""// Generated by run_rules.py; independent free inputs latched once.
module rules_equiv(input clock, {ports}, output reg bad, output reg done_seen);
reg [8:0] phase;
wire reset = phase == 0;
wire done_port;
wire [{width-1}:0] hls_o;
{regs}
{hls} u_hls(.clock(clock), .reset(!reset), .start_port(phase == 1),
  .done_port(done_port), .return_port(hls_o), {args});
{body}
always @(posedge clock) begin
  phase <= phase + 1'b1;
  if (reset) begin
    {latch}
    bad <= 0;
    done_seen <= 0;
  end else if (done_port) begin
    bad <= bad | ({comparison});
    done_seen <= 1;
  end
end
endmodule
"""


def access(base, top):
    body = """
tlul_pkg::tl_h2d_t req;
always_comb begin
  req = '0;
  req.a_address = addr;
  req.a_opcode = tlul_pkg::tl_a_op_e'(op);
  req.a_size = size;
end
wire allowed;
cheriot_access_check u_rtl(.clk_i(clock), .rst_ni(1'b1),
  .cheriot_ena_i(ena), .tl_h_i(req), .tl_d_i('0), .allow_forward(allowed));
"""
    wrapper = miter("access_rules_hls", dict(addr=32, op=3, size=2, ena=4),
                    dict(addr="addr", base=lit(base), top=lit(top), op="{29'b0,op}",
                         size="{30'b0,size}", ena="{28'b0,ena}"), 32, body,
                    "allowed != hls_o[0]")
    return "cheriot_access_check", {"CheriotBaseAddr": base, "CheriotTopAddr": top}, [], ["allow_forward"], wrapper


def tag_map(values):
    sb, st, nb, nt, mb = values
    nvm_off, sram_off = (st-sb)//64, (st-sb)//64+(nt-nb)//64
    body = """
tlul_pkg::tl_h2d_t req;
always_comb begin req = '0; req.a_address = addr; end
wire [31:0] stem, meta;
wire is_tagged, is_nvm;
cheriot_tag_filter u_rtl(.clk_i(clock), .rst_ni(1'b1), .tl_d_i(req),
  .tl_h_i('0), .tl_m_i('0), .tag_d_i(1'b0), .tag_m_i(1'b0),
  .cheriot_ena_i(4'h6), .addr_stem(stem), .meta_addr(meta),
  .addr_tagged(is_tagged), .addr_nvm(is_nvm));
"""
    wrapper = miter("tag_map_hls", dict(addr=32),
                    dict(addr="addr", sb=lit(sb), st=lit(st), nb=lit(nb), nt=lit(nt), mb=lit(mb)),
                    64, body, "{stem[7:3],meta,is_nvm,is_tagged} != hls_o[38:0]")
    params = dict(MainSramBaseAddr=sb, MainSramTopAddr=st, NvmBaseAddr=nb, NvmTopAddr=nt,
                  MetaMainSramTagBase=mb+sram_off, MetaNvmTagBase=mb+nvm_off)
    return "cheriot_tag_filter", params, [], ["addr_stem", "meta_addr", "addr_tagged", "addr_nvm"], wrapper


def wtrc():
    body = r"""
tlul_pkg::tl_h2d_t req;
tlul_pkg::tl_d2h_t rsp, own;
always_comb begin
  req = '0;
  req.a_address = addr;
  req.a_opcode = tlul_pkg::tl_a_op_e'(ctl[3:1]);
  req.a_size = ctl[5:4];
  req.a_mask = ctl[9:6];
  req.a_data = expected;
  req.a_user.data_intg = expected_intg;
  rsp = '0;
  rsp.d_error = ctl[11];
  rsp.d_valid = ctl[13];
  rsp.d_data = actual;
  rsp.d_user.data_intg = actual_intg;
end
wire [41:0] expectation;
wire mismatch, tag_req, seq_bad;
cheriot_wtrc u_rtl(.clk_i(clock), .rst_ni(1'b1),
  .tl_d_i(req), .tl_h_i(rsp), .cap_store_i(1'b1), .req_done_i(1'b0), .m_ready_i(1'b1),
  .\cap_state_q.i ({1'b0,ctl[0]}), .\cap_q.i (previous_addr[31:3]),
  .\cmd_intg_err.i (ctl[10]), .\exp_rsp_valid.i (1'b1),
  .\exp_rsp.i ({1'b1,addr[2],expectation[39],expected,expected_intg}),
  .\w0_ok_q.i (ctl[12]), .exp_req(expectation), .seq_violation(seq_bad),
  .mismatch(mismatch), .own_rsp(own), .tag_wr_req(tag_req));
"""
    inputs = dict(addr=32, previous_addr=32, ctl=14, expected=32, actual=32,
                  expected_intg=7, actual_intg=7)
    args = {name: name if bits == 32 else f"{{{32-bits}'b0,{name}}}" for name, bits in inputs.items()}
    wrapper = miter("wtrc_match_hls", inputs, args, 32, body,
                    "{seq_bad,!mismatch,tag_req,!own.d_error,expectation[39]} != hls_o[4:0]")
    cuts = ["cap_state_q", "cap_q", "cmd_intg_err", "exp_rsp_valid", "exp_rsp", "w0_ok_q"]
    return "cheriot_wtrc", {}, cuts, ["exp_req", "seq_violation", "mismatch", "own_rsp", "tag_wr_req"], wrapper


def run(command, log, cwd):
    start = time.monotonic()
    with log.open("w") as out:
        result = subprocess.run(command, cwd=cwd, stdout=out, stderr=subprocess.STDOUT)
    return result.returncode, round(time.monotonic()-start, 3)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--family", choices=["access", "tag", "wtrc", "all"], default="all")
    args = parser.parse_args()
    build = args.build.resolve()
    build.mkdir(parents=True, exist_ok=True)
    cases = []
    for map_name, values in MAPS.items():
        sb, st, nb, nt, mb = values
        revbm, tags = (st-sb)//64, (st-sb)//64+(nt-nb)//64
        if args.family in ("access", "all"):
            for region, lo, hi in (("bitmap", mb, mb+revbm), ("tags", mb+revbm, mb+revbm+tags)):
                cases.append((f"access_{map_name}_{region}", "access_rules_hls", access(lo, hi), None))
        if args.family in ("tag", "all"):
            cases.append((f"tag_{map_name}", "tag_map_hls", tag_map(values), None))
    if args.family in ("wtrc", "all"):
        cases.append(("wtrc", "wtrc_match_hls", wtrc(), None))
    mutations = {
        "access_eg2_bitmap": [("inclusive_top", "<  CheriotTopAddr", "<= CheriotTopAddr")],
        "tag_eg2": [("wrong_bit", "tl_d_i.a_address - MainSramBaseAddr;", "(tl_d_i.a_address - MainSramBaseAddr) ^ 32'h8;"),
                    ("wrong_word", "<< 32'd2", "<< 32'd3")],
        "wtrc": [("ignore_w0", "head_w1 && !mismatch && w0_ok_q;", "head_w1 && !mismatch;"),
                 ("invalid_response", "tl_h_i.d_valid && head_w1 && !mismatch", "head_w1 && !mismatch")],
    }
    for name, hls, config, _ in list(cases):
        for mutation in mutations.get(name, []):
            cases.append((name+"_negative_"+mutation[0], hls, config, mutation))
    results = []
    hls_times = {}
    for hls in sorted({case[1] for case in cases}):
        directory = build/hls
        directory.mkdir(exist_ok=True)
        output = directory/(hls+".v")
        sources = [HERE/(hls+".c"), HERE/"../cmodel/cms_rules.h"]
        if not output.exists() or any(p.stat().st_mtime > output.stat().st_mtime for p in sources):
            rc, elapsed = run([os.environ.get("BAMBU", "bambu"), str(sources[0]),
                               "-I"+str(HERE/"../cmodel"), "-O3", "--top-fname="+hls,
                               "--top-rtldesign-name="+hls], directory/"bambu.log", directory)
            if rc:
                raise SystemExit(f"Bambu failed: {directory/'bambu.log'}")
            hls_times[hls] = elapsed
        print(f"HLS ready: {hls}", flush=True)
    for name, hls, (module, params, cuts, exposes, wrapper), mutation in cases:
        rtl = ROOT/f"hw/ip/cheriot_mem_sys/rtl/{module}.sv"
        directory = build/name
        directory.mkdir(exist_ok=True)
        if mutation:
            source = rtl.read_text()
            _, old, new = mutation
            if old not in source:
                raise SystemExit(f"Mutation did not match: {name}")
            rtl = directory/(module+".sv")
            rtl.write_text(source.replace(old, new))
        sv = directory/"rules_equiv.sv"
        sv.write_text(wrapper)
        parameters = " ".join(f"-G {key}={value}" for key, value in params.items())
        files = (HERE/"../edagen/cheriot_mem_sys_rtl.f").read_text()
        files = files.replace("${REPO}", str(ROOT))
        original = ROOT/f"hw/ip/cheriot_mem_sys/rtl/{module}.sv"
        files = files.replace(str(original), str(rtl))
        filelist = directory/"rtl.f"
        filelist.write_text(files)
        commands = [f"read_slang --top {module} {parameters} -f {filelist}",
                    "proc", "flatten"]
        if cuts:
            commands.append("expose -cut " + " ".join(module+"/"+s for s in cuts))
        commands += ["expose " + " ".join(module+"/"+s for s in exposes),
                     f"read_verilog {build/hls/(hls+'.v')}",
                     "read_slang --top rules_equiv " + " ".join(PACKAGES) + f" {sv}",
                     "prep -top rules_equiv", "flatten", "memory_map", "async2sync", "opt -full",
                     "hierarchy -check", "check -assert",
                     f"sat -verify -seq 64 -enable_undef -set-def-inputs -set-init-zero -prove bad 0 -show-inputs -show-outputs -dump_vcd {directory/'counterexample.vcd'}",
                     "sat -verify -seq 64 -enable_undef -set-def-inputs -set-init-zero -prove-skip 63 -prove done_seen 1"]
        ys = directory/"prove.ys"
        ys.write_text("\n".join(commands)+"\n")
        rc, elapsed = run([os.environ.get("YOSYS", "yosys"), "-m", os.environ["YOSYS_SLANG"],
                           "-s", str(ys)], directory/"yosys.log", ROOT)
        log = (directory/"yosys.log").read_text()
        passed = (rc != 0 and "model found: FAIL" in log) if mutation else (
            rc == 0 and log.count("no model found: SUCCESS") == 2)
        result = dict(case=name, negative=bool(mutation), passed=passed, seconds=elapsed)
        results.append(result)
        (build/"summary.json").write_text(json.dumps(dict(hls_seconds=hls_times, results=results), indent=2)+"\n")
        print(f"{name}: {'PASS (expected counterexample)' if passed and mutation else 'PASS' if passed else 'FAIL'} ({elapsed}s)", flush=True)
        if not passed:
            print("\n".join(log.splitlines()[-45:]))
            raise SystemExit(1)


if __name__ == "__main__":
    main()
